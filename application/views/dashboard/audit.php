<?php
defined('BASEPATH') OR exit('No direct script access allowed');

$entries = isset($entries) && is_array($entries) ? $entries : [];
$total = (int) ($total ?? 0);
$actions = [
    'user.create' => 'Usuario creado',
    'user.update' => 'Usuario actualizado',
    'user.activate' => 'Usuario activado',
    'user.deactivate' => 'Usuario desactivado',
    'user.mfa_enable' => 'Verificación en dos pasos activada',
    'user.mfa_disable' => 'Verificación en dos pasos desactivada',
    'user.mfa_reset' => 'Verificación en dos pasos restablecida',
    'group.create' => 'Grupo creado',
    'group.update' => 'Grupo actualizado',
    'api_key.create' => 'Clave de API creada',
    'api_key.revoke' => 'Clave de API revocada',
    'settings.update' => 'Ajustes modificados',
];
$fields = [
    'first_name' => 'nombre', 'last_name' => 'apellido', 'email' => 'correo', 'phone' => 'teléfono',
    'company' => 'empresa', 'password' => 'contraseña', 'name' => 'nombre', 'description' => 'descripción',
];
$targets = ['user' => 'Usuario', 'group' => 'Grupo', 'api_key' => 'Clave de API', 'settings' => 'Configuración'];
$this->load->view('dashboard/_header', [
    'page_title' => 'Auditoría',
    'active_nav' => 'audit',
    'settings' => $settings ?? [],
]);
?>
<div class="page-heading">
    <div>
        <p class="eyebrow">Control de acceso</p>
        <h1>Auditoría</h1>
        <p class="page-description">Cambios en cuentas, grupos, claves y ajustes. Solo se registran los nombres de los campos, nunca sus valores.</p>
    </div>
</div>

<section class="panel" aria-labelledby="audit-heading">
    <div class="panel-heading">
        <div><p class="eyebrow">Registro</p><h2 id="audit-heading"><?php echo $total === 1 ? '1 entrada' : $total . ' entradas'; ?></h2></div>
    </div>
    <?php if ($entries === []): ?>
    <div class="empty-state">
        <span class="empty-icon" aria-hidden="true">☰</span>
        <h3>Todavía no hay actividad</h3>
        <p>Los cambios administrativos aparecerán aquí.</p>
    </div>
    <?php else: ?>
    <div class="table-scroll">
        <table class="data-table">
            <thead><tr><th scope="col">Fecha</th><th scope="col">Responsable</th><th scope="col">Acción</th><th scope="col">Objetivo</th><th scope="col">Detalle</th></tr></thead>
            <tbody>
            <?php foreach ($entries as $entry):
                $notes = [];
                if ($entry->fields !== []) {
                    $notes[] = 'Campos: ' . implode(', ', array_map(static function ($field) use ($fields) {
                        return $fields[$field] ?? $field;
                    }, $entry->fields));
                }
                if ($entry->group_names !== []) {
                    $notes[] = 'Grupos: ' . implode(', ', $entry->group_names);
                }
                if ($entry->setting_keys !== []) {
                    $notes[] = 'Ajustes: ' . implode(', ', $entry->setting_keys);
                }
                $target = $targets[$entry->target_type] ?? (string) $entry->target_type;
                $target_name = $entry->target_label ?? ($entry->target_type === 'settings' ? '' : '#' . (int) $entry->target_id);
            ?>
            <tr>
                <td data-label="Fecha"><?php echo html_escape(date('d/m/Y H:i', (int) $entry->created_at)); ?></td>
                <td data-label="Responsable"><?php echo $entry->actor_email !== NULL ? html_escape($entry->actor_email) : '<span class="muted">#' . (int) $entry->actor_user_id . '</span>'; ?></td>
                <td data-label="Acción"><span class="tag"><?php echo html_escape($actions[$entry->action] ?? (string) $entry->action); ?></span></td>
                <td data-label="Objetivo"><?php echo html_escape(trim($target . ' ' . $target_name)); ?></td>
                <td data-label="Detalle"><?php echo $notes === [] ? '<span class="muted">—</span>' : html_escape(implode(' · ', $notes)); ?></td>
            </tr>
            <?php endforeach; ?>
            </tbody>
        </table>
    </div>
    <?php if (!empty($pagination)): ?>
    <nav class="pagination" aria-label="Páginas de auditoría"><?php echo $pagination; // Generated by CI Pagination with server-controlled URL configuration. ?></nav>
    <?php endif; ?>
    <?php endif; ?>
</section>
<?php $this->load->view('dashboard/_footer'); ?>
